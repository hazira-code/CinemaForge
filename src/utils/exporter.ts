import jsPDF from 'jspdf';
import confetti from 'canvas-confetti';
import { MovieProject } from '../types';

export function triggerConfetti() {
  confetti({
    particleCount: 80,
    spread: 70,
    origin: { y: 0.6 },
    colors: ['#3B82F6', '#8B5CF6', '#EC4899', '#06B6D4', '#10B981'],
  });
}

export function downloadJSON(project: MovieProject) {
  const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(project, null, 2));
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  downloadAnchor.setAttribute('download', `${project.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}_cinema_package.json`);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
  triggerConfetti();
}

