export function downloadPDF(project: MovieProject) {
  const doc = new jsPDF({
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 50;

  // Header
  doc.setFillColor(11, 15, 25);
  doc.rect(0, 0, pageWidth, 80, 'F');

  doc.setTextColor(59, 130, 246);
  doc.setFontSize(22);
  doc.text('PROMPT CINEMA AI', 40, 42);

  doc.setTextColor(200, 200, 220);
  doc.setFontSize(10);
  doc.text('HOLLYWOOD-GRADE PRE-PRODUCTION PACKAGE', 40, 60);

  y = 110;

  // Title & Logline
  doc.setTextColor(30, 30, 40);
  doc.setFontSize(18);
  doc.text(project.title.toUpperCase(), 40, y);
  y += 20;

  doc.setFontSize(11);
  doc.setTextColor(80, 80, 100);
  doc.text(`Genre: ${project.genre}`, 40, y);
  y += 18;

  doc.setFontSize(10);
  doc.setTextColor(50, 50, 60);
  const splitLogline = doc.splitTextToSize(`Logline: ${project.logline}`, pageWidth - 80);
  doc.text(splitLogline, 40, y);
  y += splitLogline.length * 14 + 20;

  // Synopsis
  doc.setFontSize(12);
  doc.setTextColor(139, 92, 246);
  doc.text('1. STORY SYNOPSIS', 40, y);
  y += 16;

  doc.setFontSize(9);
  doc.setTextColor(40, 40, 50);
  const splitSynopsis = doc.splitTextToSize(project.synopsis, pageWidth - 80);
  doc.text(splitSynopsis, 40, y);
  y += splitSynopsis.length * 12 + 25;

  // Check Page break
  if (y > 700) {
    doc.addPage();
    y = 50;
  }

  // Screenplay preview
  doc.setFontSize(12);
  doc.setTextColor(139, 92, 246);
  doc.text('2. SCREENPLAY SCENES', 40, y);
  y += 18;

  project.screenplay.slice(0, 3).forEach((scene) => {
    if (y > 720) {
      doc.addPage();
      y = 50;
    }
    doc.setFontSize(10);
    doc.setTextColor(20, 20, 25);
    doc.text(`SCENE ${scene.sceneNumber}: ${scene.heading}`, 40, y);
    y += 14;

    doc.setFontSize(9);
    doc.setTextColor(60, 60, 70);
    const splitAction = doc.splitTextToSize(scene.action, pageWidth - 80);
    doc.text(splitAction, 40, y);
    y += splitAction.length * 12 + 10;

    scene.dialogueLines.forEach((d) => {
      if (y > 740) {
        doc.addPage();
        y = 50;
      }
      doc.setFontSize(9);
      doc.setTextColor(10, 10, 10);
      doc.text(d.character.toUpperCase(), pageWidth / 2, y, { align: 'center' });
      y += 12;
      if (d.parenthetical) {
        doc.text(d.parenthetical, pageWidth / 2, y, { align: 'center' });
        y += 12;
      }
      const splitLine = doc.splitTextToSize(`"${d.line}"`, pageWidth - 200);
      doc.text(splitLine, pageWidth / 2, y, { align: 'center' });
      y += splitLine.length * 12 + 12;
    });

    y += 10;
  });

  // Footer on all pages
  const totalPages = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 160);
    doc.text(`Prompt Cinema AI — Page ${i} of ${totalPages}`, pageWidth - 160, 820);
  }

  doc.save(`${project.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}_filmmaking_package.pdf`);
  triggerConfetti();
}

export function downloadRenderConfig(project: MovieProject) {
  const yamlContent = `services:
  - type: web
    name: ${project.title.toLowerCase().replace(/[^a-z0-9]/g, '-')}-cinema
    runtime: node
    plan: free
    buildCommand: npm install && npm run build
    startCommand: npm start
    envVars:
      - key: NODE_ENV
        value: production
      - key: NPM_CONFIG_PRODUCTION
        value: "false"
      - key: GEMINI_API_KEY
        sync: false
`;

  const blob = new Blob([yamlContent], { type: 'text/yaml' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `render.yaml`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
  triggerConfetti();
}

